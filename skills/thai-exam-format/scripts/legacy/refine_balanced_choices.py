keys_dist = {1: 0, 2: 0, 3: 0, 4: 0}
final_items = []

for item in questions_data:
    sorted_choices = sorted(item["choices"], key=lambda x: thai_visual_len(x[0]))
    correct_pos = None
    for idx, (text, is_correct) in enumerate(sorted_choices, 1):
        if is_correct:
            correct_pos = idx
            break
            
    keys_dist[correct_pos] += 1
    lengths = [thai_visual_len(c[0]) for c in sorted_choices]
    diff = max(lengths) - min(lengths)
    match_target = (correct_pos == item["target_key"])
    
    status_icon = "🟢" if match_target else "🔴"
    print(f"{status_icon} Q{item['num']:02d}: Key={correct_pos} (Target={item['target_key']}) | Lens={lengths} (Diff={diff:2d})")
    
    final_items.append({
        "num": item["num"],
        "stem": item["stem"],
        "key": correct_pos,
        "choices": [c[0] for c in sorted_choices]
    })

print(f"\n=== FINAL KEY DISTRIBUTION ===")
for k in [1, 2, 3, 4]:
    print(f"Choice {k}: {keys_dist[k]} questions ({keys_dist[k]/40*100:.1f}%)")

