lines = [l.strip() for l in raw_text.strip().split("\n") if l.strip()]

questions = []
current_q = None

for line in lines:
    if line.startswith("ผลการเรียนรู้"):
        continue
    m = re.match(r'^(\d+)\.\s*(.*)', line)
    if m:
        if current_q:
            questions.append(current_q)
        q_num = int(m.group(1))
        q_text = m.group(2).strip()
        current_q = {
            'num': q_num,
            'text': q_text,
            'choices': []
        }
    else:
        if current_q:
            # Choice line
            c_text = re.sub(r'^[1-4][\.\)]\s*', '', line).strip()
            current_q['choices'].append(c_text)

if current_q:
    questions.append(current_q)

print(f"Total questions parsed: {len(questions)}")
for q in questions:
    if len(q['choices']) != 4:
        print(f"WARNING: Question {q['num']} has {len(q['choices'])} choices!")
    
    # Sort choices by visual length
    sorted_choices = sorted(q['choices'], key=lambda c: (visual_length(c), len(c)))
    q['sorted_choices'] = sorted_choices

with open(os.path.join(BASE_DIR, "scripts", "job02_new_parsed.json"), "w", encoding="utf-8") as f:
    json.dump(questions, f, ensure_ascii=False, indent=2)

